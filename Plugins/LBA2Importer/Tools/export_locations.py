"""Exports lba2remake's location tree (planets > islands > scenes, the remake's teleport menu) to
Resources/CommunityMetadata/lba2_locations.json and rasterizes its location icons for the travel menu.

Usage: export_locations.py [remake checkout]   (default: env LBA2_REMAKE, else ../refs/lba2remake, ../lba2remake)
The icons are written to Saved/LookDev/locations/*.png (SVG rendered by headless Edge); import_location_icons.py
turns them into the plugin's textures.
"""
import json, os, re, subprocess, sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(TOOLS)
PROJECT = os.path.dirname(os.path.dirname(PLUGIN))
OUT_JSON = os.path.join(PLUGIN, "Resources", "CommunityMetadata", "lba2_locations.json")
OUT_ICONS = os.path.join(PROJECT, "Saved", "LookDev", "locations")
EDGE = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"

# File, exported constant (Twinsun.ts holds both games' trees).
SOURCES = [("Twinsun.ts", "TwinsunLBA2"), ("Moon.ts", "Moon"), ("ZeelishSurface.ts", "ZeelishSurface"),
           ("ZeelishUndergas.ts", "ZeelishUndergas")]
# Scene numbers the remake places elsewhere than SCENE.HQR's headers: its Otringal "Baldino's Landing Zone" is 94,
# a Citadel cube (the sea travel, island 0) in the data; Otringal's landing zone is 138 (island 4), which the
# remake calls a demo copy.
CORRECTIONS = {94: 138}
# Icon file -> size in pixels: twice the size the menu draws it at.
ICONS = {"twinsun": 96, "moon": 96, "zeelish": 96, "undergas": 96, "island": 32, "section": 32, "building": 32}


def find_remake():
    if len(sys.argv) > 1:
        return sys.argv[1]
    candidates = [os.environ.get("LBA2_REMAKE", ""), os.path.join(PROJECT, "..", "refs", "lba2remake"),
                  os.path.join(PROJECT, "..", "lba2remake")]
    for candidate in candidates:
        if candidate and os.path.isdir(os.path.join(candidate, "src")):
            return os.path.abspath(candidate)
    sys.exit("lba2remake checkout not found (pass its path or set LBA2_REMAKE)")


def scene(kind, index, name, children=None):
    return {"kind": kind, "scene": index, "name": name, "children": children or []}


def island(index, name, island_id, children):
    return {"name": name, "id": island_id, "children": children}


def planet(name, icon, children):
    return {"name": name, "icon": icon, "islands": children}


def parse_tree(path, const):
    text = open(path, encoding="utf-8").read()
    match = re.search(r"const %s\s*=\s*(planet\(.*?\n\]\));" % const, text, re.S)
    if not match:
        sys.exit("no %s in %s" % (const, path))
    # The tree is plain calls of string and number literals: valid Python once the helpers are named.
    expression = match.group(1)
    return eval(expression, {"planet": planet, "island": island, "section": lambda *a: scene("section", *a),
                             "iso": lambda *a: scene("building", *a)})


def strip_demo(nodes):
    """The remake's menu hides the attract-mode copies ([DEMO] names); so does ours."""
    kept = []
    for node in nodes:
        if node["name"].startswith("[DEMO]"):
            continue
        if "scene" in node:
            node["scene"] = CORRECTIONS.get(node["scene"], node["scene"])
        node["children"] = strip_demo(node["children"])
        kept.append(node)
    return kept


def export_tree(remake):
    folder = os.path.join(remake, "src", "ui", "editor", "areas", "gameplay", "locator", "locations")
    planets = [parse_tree(os.path.join(folder, file), const) for file, const in SOURCES]
    for p in planets:
        p["islands"] = strip_demo(p["islands"])
    data = {
        "_attribution": "Location tree of lba2remake's teleport menu (https://github.com/LBALab/lba2remake, "
                        "src/ui/editor/areas/gameplay/locator/locations), MIT License. Names only; no game data. "
                        "Generated by Tools/export_locations.py.",
        "planets": planets,
    }
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    count = 0
    def walk(nodes):
        nonlocal count
        for node in nodes:
            count += 1
            walk(node["children"])
    for p in planets:
        for i in p["islands"]:
            walk(i["children"])
    print("wrote %s (%d planets, %d scenes)" % (OUT_JSON, len(planets), count))


def export_icons(remake):
    os.makedirs(OUT_ICONS, exist_ok=True)
    for icon, size in ICONS.items():
        svg = os.path.join(remake, "www", "editor", "icons", "locations", icon + ".svg")
        page = os.path.join(OUT_ICONS, icon + ".html")
        with open(page, "w", encoding="utf-8") as f:
            f.write('<html><body style="margin:0;background:transparent">'
                    '<img src="file:///%s" style="width:%dpx;height:%dpx;display:block"></body></html>'
                    % (svg.replace("\\", "/"), size, size))
        png = os.path.join(OUT_ICONS, "T_Location_%s.png" % icon.capitalize())
        subprocess.run([EDGE, "--headless", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files",
                        "--default-background-color=00000000", "--force-device-scale-factor=1",
                        "--window-size=%d,%d" % (size, size), "--screenshot=" + png, "file:///" + page.replace("\\", "/")],
                       check=True, capture_output=True)
        os.remove(page)
        print("wrote", png)


if __name__ == "__main__":
    remake = find_remake()
    export_tree(remake)
    export_icons(remake)
